#!/usr/bin/env python3
"""Build one compact XMLTV guide containing only channels in our Arvio playlist."""
import gzip
import json
import sqlite3
import re
import tempfile
import xml.etree.ElementTree as ET
from datetime import datetime, timedelta, timezone
from pathlib import Path
from urllib.request import Request, urlopen

ROOT = Path(__file__).resolve().parent
# Samsung/Pluto are known working sources. Optional Roku/Plex may fail or lack matches.
SOURCES = [
    ("Samsung", "https://i.mjh.nz/SamsungTVPlus/us.xml.gz", True),
    ("Pluto", "https://i.mjh.nz/PlutoTV/us.xml.gz", True),
    ("Roku", "https://i.mjh.nz/Roku/all.xml.gz", False),
    ("Plex", "https://i.mjh.nz/Plex/us.xml.gz", False),
    # Independent XMLTV feeds; availability and actual channel coverage are audited.
    ("EPGShare US Alt", "https://epgshare01.online/epgshare01/epg_ripper_US2.xml.gz", False),
    ("EPGShare Brazil", "https://epgshare01.online/epgshare01/epg_ripper_BR1.xml.gz", False),
]

# Third-party guides used only to fill channels that none of SOURCES cover. Each playlist
# tvg-id is mapped to one reviewed guide channel; rows are copied under the playlist ID.
SUPPLEMENTAL = [
    ("EPGTalk US", "https://raw.githubusercontent.com/acidjesuz/EPGTalk/master/US_guide.xml.gz"),
    ("EPGTalk FreeTV", "https://raw.githubusercontent.com/acidjesuz/EPGTalk/master/FreeTV_guide.xml.gz"),
]
ALIASES = {
    "AE.us@East": "I265.10035.schedulesdirect.org",
    "E.us@East": "I236.10989.schedulesdirect.org",
    "MTV.us@East": "I160.10986.gracenote.com",
    "GameShowNetwork.us@East": "I233.14909.schedulesdirect.org",
    "IONPlus.us@East": "117518.SamsungTVPlus",
    "WipeoutXtra.us@SD": "113735.SamsungTVPlus",
    "692090": "128388.Plex",  # FilmRise Horror
}

# Optional XMLTV generated by chris102994/toonamiaftermath-cli in the workflow. Its channel IDs
# are positional numbers, so channels are mapped by display name. Absent file = skipped.
TOONAMI_FILE = ROOT / "toonami.xml"
TOONAMI_TARGETS = {"east": ("ToonamiAftermath.us@East", "Toonami Aftermath East"),
                   "west": ("ToonamiAftermath.us@West", "Toonami Aftermath West")}

def read_toonami(path, db):
    """Insert Toonami East/West programmes under the playlist IDs; return {target: count}."""
    root = ET.parse(path).getroot()
    targets = {}
    for channel in root.findall("channel"):
        name = " ".join(n.text or "" for n in channel.findall("display-name")).lower()
        if "radio" in name:
            continue
        for word, target in TOONAMI_TARGETS.items():
            if word in name:
                targets[channel.get("id")] = target[0]
    counts = {}
    for programme in root.findall("programme"):
        target = targets.get(programme.get("channel"))
        if not target or not programme.get("start") or not (programme.findtext("title") or "").strip():
            continue
        programme.set("channel", target)
        db.execute("INSERT OR IGNORE INTO programmes VALUES (?, ?, ?, ?)",
                   (target, programme.get("start"), programme.get("stop") or "",
                    ET.tostring(programme, encoding="utf-8")))
        counts[target] = counts.get(target, 0) + 1
    for target, label in TOONAMI_TARGETS.values():
        if target not in counts:
            continue
        channel = ET.Element("channel", id=target)
        ET.SubElement(channel, "display-name").text = label
        db.execute("INSERT OR IGNORE INTO channels VALUES (?, ?)", (target, ET.tostring(channel, encoding="utf-8")))
    db.commit()
    return counts

def apply_aliases(db, aliases):
    """Copy a guide channel's rows under the playlist tvg-id when that ID has no programmes."""
    results = {}
    for target, source in aliases.items():
        if db.execute("SELECT 1 FROM programmes WHERE id=? LIMIT 1", (target,)).fetchone():
            results[target] = {"status": "already_covered"}
            continue
        row = db.execute("SELECT xml FROM channels WHERE id=?", (source,)).fetchone()
        entries = db.execute("SELECT start, stop, xml FROM programmes WHERE id=?", (source,)).fetchall()
        if row is None or not entries:
            results[target] = {"status": "source_missing", "source": source}
            continue
        channel = ET.fromstring(row[0])
        channel.set("id", target)
        db.execute("INSERT OR IGNORE INTO channels VALUES (?, ?)",
                   (target, ET.tostring(channel, encoding="utf-8")))
        for start, stop, xml in entries:
            programme = ET.fromstring(xml)
            programme.set("channel", target)
            db.execute("INSERT OR IGNORE INTO programmes VALUES (?, ?, ?, ?)",
                       (target, start, stop, ET.tostring(programme, encoding="utf-8")))
        results[target] = {"status": "aliased", "source": source, "programmes": len(entries)}
    db.commit()
    return results

def playlist_channels():
    result = {}
    for line in (ROOT / "arvio.m3u").read_text(encoding="utf-8").splitlines():
        if not line.startswith("#EXTINF:"):
            continue
        match = re.search(r'tvg-id="([^"]+)"', line)
        if match:
            result[match.group(1)] = line.rsplit(",", 1)[-1].strip()
    return result

def read_source(url, db, keep=None):
    req = Request(url, headers={"User-Agent": "ArvioPlaylistEPG/1.0"})
    with urlopen(req, timeout=120) as response:
        with tempfile.TemporaryFile() as tmp:
            while True:
                chunk = response.read(1024 * 1024)
                if not chunk:
                    break
                tmp.write(chunk)
            tmp.seek(0)
            magic = tmp.read(2)
            tmp.seek(0)
            stream = gzip.GzipFile(fileobj=tmp) if magic == bytes((31, 139)) else tmp
            added = 0
            for _, elem in ET.iterparse(stream, events=("end",)):
                if keep is not None and elem.tag in ("channel", "programme") and \
                        (elem.get("id") if elem.tag == "channel" else elem.get("channel")) not in keep:
                    pass
                elif elem.tag == "channel" and elem.get("id"):
                    db.execute("INSERT OR IGNORE INTO channels VALUES (?, ?)",
                               (elem.get("id"), ET.tostring(elem, encoding="utf-8")))
                elif elem.tag == "programme" and elem.get("channel"):
                    cursor = db.execute("INSERT OR IGNORE INTO programmes VALUES (?, ?, ?, ?)",
                                        (elem.get("channel"), elem.get("start"), elem.get("stop"),
                                         ET.tostring(elem, encoding="utf-8")))
                    added += cursor.rowcount
                if elem.tag in ("channel", "programme"):
                    elem.clear()
            db.commit()
            return added

def main():
    wanted = playlist_channels()
    source_status = {}
    with tempfile.TemporaryDirectory() as folder:
        db = sqlite3.connect(str(Path(folder) / "epg.sqlite"))
        db.execute("CREATE TABLE channels (id TEXT PRIMARY KEY, xml BLOB)")
        db.execute("CREATE TABLE programmes (id TEXT, start TEXT, stop TEXT, xml BLOB, PRIMARY KEY(id, start, stop))")
        for name, url, required in SOURCES:
            try:
                count = read_source(url, db)
                source_status[name] = {"status": "ok", "new_programmes": count}
                print(f"{name}: {count} new programmes", flush=True)
            except Exception as exc:
                source_status[name] = {"status": "unavailable", "reason": str(exc)[:180]}
                if required:
                    raise RuntimeError(f"Required {name} EPG unavailable; preserving old guide") from exc
                print(f"Skipping optional {name}: {exc}", flush=True)
        wanted_sources = set(ALIASES.values())
        for name, url in SUPPLEMENTAL:
            try:
                count = read_source(url, db, keep=wanted_sources)
                source_status[name] = {"status": "ok", "new_programmes": count}
                print(f"{name}: {count} new programmes", flush=True)
            except Exception as exc:
                source_status[name] = {"status": "unavailable", "reason": str(exc)[:180]}
                print(f"Skipping supplemental {name}: {exc}", flush=True)
        if TOONAMI_FILE.exists():
            try:
                counts = read_toonami(TOONAMI_FILE, db)
                source_status["Toonami Aftermath"] = {"status": "ok", "programmes": counts}
                print(f"Toonami Aftermath: {counts}", flush=True)
            except Exception as exc:
                source_status["Toonami Aftermath"] = {"status": "unavailable", "reason": str(exc)[:180]}
                print(f"Skipping Toonami Aftermath: {exc}", flush=True)
        alias_results = apply_aliases(db, {t: s for t, s in ALIASES.items() if t in wanted})
        programmes = db.execute("SELECT COUNT(*) FROM programmes").fetchone()[0]
        if programmes < 100:
            raise RuntimeError("Guide too small; preserving previous guide")
        # Export only playlist channels and a bounded, current programme window.
        # The former unfiltered export was 14 MB / 218k programmes and broke guide loading.
        now = datetime.now(timezone.utc)
        cutoff = (now - timedelta(hours=6)).strftime("%Y%m%d%H%M%S")
        horizon = (now + timedelta(days=7)).strftime("%Y%m%d%H%M%S")
        selected = set(wanted)
        covered = set()
        exported_programmes = 0
        path = ROOT / "epg.xml.gz"
        with path.open("wb") as raw:
            with gzip.GzipFile(fileobj=raw, mode="wb", filename="", mtime=0, compresslevel=6) as out:
                out.write(b'<?xml version="1.0" encoding="UTF-8"?>\n<tv generator-info-name="Arvio-Playlist">\n')
                for cid, xml in db.execute("SELECT id, xml FROM channels"):
                    if cid in selected:
                        out.write(xml + b"\n")
                for cid, start, stop, xml in db.execute("SELECT id, start, stop, xml FROM programmes"):
                    if cid in selected and start[:14] <= horizon and (not stop or stop[:14] >= cutoff):
                        out.write(xml + b"\n")
                        covered.add(cid)
                        exported_programmes += 1
                out.write(b"</tv>\n")
        if exported_programmes < 1000 or len(covered) < 200:
            path.unlink(missing_ok=True)
            raise RuntimeError(f"Compact guide incomplete: {len(covered)} channels, {exported_programmes} programmes")
        # Diagnose missing matches against real XMLTV channel IDs and display names.
        missing = {cid: name for cid, name in wanted.items() if cid not in covered}
        candidates = {}
        def clean(value):
            value = re.sub(r"\\s*\\[.*?\\]", "", value)
            value = re.sub(r"\\s*\\(\\d+p\\)", "", value)
            return re.sub(r"[^a-z0-9]", "", value.lower())
        guide_index = []
        for cid, xml in db.execute("SELECT id, xml FROM channels"):
            node = ET.fromstring(xml)
            names = [n.text or "" for n in node.findall("display-name")]
            guide_index.append((cid, names))
        for cid, name in missing.items():
            desired = clean(name)
            base_id = clean(cid.split("@")[0])
            found = []
            for guide_id, names in guide_index:
                matched = (clean(guide_id) == base_id or
                           clean(guide_id.split("@")[0]) == base_id or
                           any(clean(n) == desired for n in names))
                if matched:
                    found.append({"id": guide_id, "names": names[:3],
                                  "has_programmes": guide_id in covered})
            candidates[name] = found[:30]
        audit = {
            "playlist_channels": len(wanted),
            "channels_with_programmes": sum(cid in covered for cid in wanted),
            "programmes": exported_programmes,
            "total_guide_channels": db.execute("SELECT COUNT(*) FROM channels").fetchone()[0],
            "sources": source_status,
            "aliases": alias_results,
            "missing_channel_candidates": candidates,
            "without_guide": [name for cid, name in wanted.items() if cid not in covered],
        }
        (ROOT / "epg-audit.json").write_text(json.dumps(audit, indent=2) + chr(10), encoding="utf-8")
        print(json.dumps(audit, indent=2))

if __name__ == "__main__":
    main()
